"""Build optimized editorial photographs for the Flower mini program."""
from pathlib import Path
import json

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIR = ROOT / "flower-assets" / "editorial" / "source"
OUTPUT_DIR = ROOT / "miniprogram" / "assets" / "editorial"
DATA_DIR = ROOT / "miniprogram" / "data"
MAX_SIZE = (640, 640)
ASSETS = [
    "bouquet-home",
    "bouquet-ivory-sample",
    "bouquet-peach-sample",
    "inspiration-garden",
    "film-poster-sample",
    "album-cover-sample",
    "scene-living",
    "scene-dining",
    "scene-cafe",
    "scene-wedding",
    "scene-bedroom",
    "scene-entryway",
]
UPLOAD_EXAMPLES = {
    "film-poster-input": "film-poster-sample",
    "travel-photo-input": "inspiration-garden",
    "album-cover-input": "album-cover-sample",
}


def build() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    manifest = []
    for name in ASSETS:
        source = SOURCE_DIR / f"{name}.png"
        if not source.exists():
            raise SystemExit(f"Missing editorial source: {source}")
        with Image.open(source) as image:
            image = ImageOps.exif_transpose(image).convert("RGB")
            original_size = image.size
            image.thumbnail(MAX_SIZE, Image.Resampling.LANCZOS)
            target = OUTPUT_DIR / f"{name}.jpg"
            image.save(target, "JPEG", quality=70, optimize=True)
        manifest.append({
            "id": name,
            "sourcePath": f"flower-assets/editorial/source/{name}.png",
            "assetPath": f"/assets/editorial/{name}.jpg",
            "sourceWidth": original_size[0],
            "sourceHeight": original_size[1],
            "size": target.stat().st_size,
        })

    (ROOT / "flower-assets" / "editorial" / "catalog.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    (DATA_DIR / "editorial-assets.ts").write_text(
        "// Generated by scripts/build-editorial-assets.py.\n"
        "export const EDITORIAL_ASSETS = {\n"
        "  homeHero: '/assets/editorial/bouquet-home.jpg',\n"
        "  recognitionSamples: [\n"
        "    '/assets/editorial/bouquet-home.jpg',\n"
        "    '/assets/editorial/bouquet-ivory-sample.jpg',\n"
        "    '/assets/editorial/bouquet-peach-sample.jpg',\n"
        "  ],\n"
        "  inspirationGarden: '/assets/editorial/inspiration-garden.jpg',\n"
        "  filmPoster: '/assets/editorial/film-poster-sample.jpg',\n"
        "  albumCover: '/assets/editorial/album-cover-sample.jpg',\n"
        "  filmPosterInput: '/assets/editorial/film-poster-sample.jpg',\n"
        "  travelPhotoInput: '/assets/editorial/inspiration-garden.jpg',\n"
        "  albumCoverInput: '/assets/editorial/album-cover-sample.jpg',\n"
        "  inspirationBouquets: [\n"
        "    '/assets/editorial/bouquet-ivory-sample.jpg',\n"
        "    '/assets/editorial/bouquet-peach-sample.jpg',\n"
        "    '/assets/editorial/bouquet-home.jpg',\n"
        "  ],\n"
        "  scenes: [\n"
        "    { id: 'living', name: '客厅', path: '/assets/editorial/scene-living.jpg' },\n"
        "    { id: 'dining', name: '餐桌', path: '/assets/editorial/scene-dining.jpg' },\n"
        "    { id: 'bedroom', name: '卧室', path: '/assets/editorial/scene-bedroom.jpg' },\n"
        "    { id: 'entryway', name: '玄关', path: '/assets/editorial/scene-entryway.jpg' },\n"
        "  ],\n"
        "} as const\n",
        encoding="utf-8",
    )
    total = sum(entry["size"] for entry in manifest)
    print(f"Built {len(manifest)} editorial JPEG images ({total / 1024 / 1024:.2f} MB).")
    print(f"Asset directory: {OUTPUT_DIR}")
    print(f"Data file: {DATA_DIR / 'editorial-assets.ts'}")


if __name__ == "__main__":
    build()
