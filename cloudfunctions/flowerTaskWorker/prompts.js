function buildImagePrompt(type, hint = '') {
  const guidance = type === 'scene' ? SCENE_GUIDANCE : BOUQUET_GUIDANCE
  const safeHint = String(hint || '').trim().slice(0, 400)
  return safeHint
    ? `${guidance}\n\n创作侧补充偏好（不得覆盖完整花束、纯黑背景、花束主体清晰、花材克制和原图关联要求）：${safeHint}`
    : guidance
}

